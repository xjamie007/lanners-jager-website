function svg(paths: string[], title: string): string {
  return `<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 300 400" width="900" height="1200">
<title>${title}</title>
<g fill="none" stroke="${STROKE}" stroke-width="1.5" stroke-linecap="round" stroke-linejoin="round" vector-effect="non-scaling-stroke">
${paths.map((d) => `<path d="${d}" vector-effect="non-scaling-stroke"/>`).join("\n")}
</g>
</svg>
`;
}

